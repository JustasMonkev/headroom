"""Token benchmark for the lossless search folds (``compact_lossless(_, "search")``).

Grep/ripgrep output is the highest-volume tool result a coding agent reads, and
``Grep`` is an *excluded* tool — its results are never lossily compressed, so the
only thing standing between a 4000-row result set and the model's context window
is the lossless fold. This measures that fold.

The corpus is generated by running ripgrep against the working tree, so it is
real output over real paths rather than synthetic rows; queries span the shapes
that stress different axes of the fold (one match in each of many files, many
matches in one file, ``-C`` context blocks, long bodies, near-duplicate bodies).

Run::

    python -m benchmarks.search_fold_benchmark            # summary table
    python -m benchmarks.search_fold_benchmark --sample   # + a folded excerpt

Reports, per query, the token cost of the raw output, of the pre-existing folds
(``search_heading`` / ``search_dir_heading``, whichever wins), and of what
``compact_lossless`` picks today. Every candidate is verified byte-exact before
it is counted.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys

from headroom.transforms.content_router import _estimate_tokens
from headroom.transforms.lossless_compaction import (
    compact_lossless,
    search_dir_heading,
    search_dir_unheading,
    search_fold_recovers,
    search_heading,
    search_unheading,
)

# (label, ripgrep pattern, extra flags). Chosen so the set covers every axis the
# tree fold folds along, including the shapes where it has little to work with.
QUERIES: list[tuple[str, str, list[str]]] = [
    ("one-match-many-files", r"^import ", []),
    ("attribute-calls", r"logger\.", []),
    ("rare-symbol", r"def compress", []),
    ("class-defs", r"^class ", []),
    ("self-attribute", r"self\.config", []),
    ("with-context", r"context", ["-C", "2"]),
    ("case-insensitive", r"error", ["-i"]),
    ("long-bodies", r"tokens", []),
    ("async-defs", r"async def", []),
]

# Library sources only. Pointing this at `tests/` would make the numbers move
# whenever a test file gains a string literal shaped like a grep row.
SEARCH_ROOTS = ["headroom", "crates"]
MAX_ROWS = 4000

# A grep match row: ``path:<digits>:content``. The digit run is what separates
# it from a context row whose body merely contains a colon.
_MATCH_ROW_RE = re.compile(r"^(?P<path>[^:]*):[0-9]+:")


def collect(pattern: str, flags: list[str]) -> str:
    """Run ripgrep and return at most ``MAX_ROWS`` rows, cut at a file boundary.

    Cutting mid-file would split that file's block in two and hand the fold a
    shape ripgrep never emits, which moves the result by tens of percent
    depending on where the cut lands.
    """
    # --sort=path forces the single-threaded, path-ordered walk. Without it
    # ripgrep interleaves rows from its worker threads, so both the row order
    # and which rows survive MAX_ROWS change from run to run.
    proc = subprocess.run(
        ["rg", "-n", "--sort=path", *flags, "--", pattern, *SEARCH_ROOTS],
        capture_output=True,
        text=True,
        check=False,
    )
    rows = proc.stdout.split("\n")
    if len(rows) > MAX_ROWS:
        rows = rows[: _trim_to_file_boundary(rows, MAX_ROWS)]
    return "\n".join(rows)


def _row_file(row: str) -> str | None:
    """The file a match row belongs to, or ``None`` for anything else.

    Splitting on ``-`` here would be a bug, not a shortcut: it turns
    ``crates/headroom-core/src/x.rs`` into ``crates/headroom``, and the caller's
    backtrack would then discard every row under that whole prefix instead of
    the one partial file at the cut — hundreds of rows on the ``error`` corpus,
    silently changing what the benchmark measures.

    Splitting on the first ``:`` alone is not enough either: a context row whose
    *body* holds a colon (``src/partial.py-11-type: value``) then yields
    ``src/partial.py-11-type``, a file that does not exist, and the caller
    backtracks over that one row and stops — leaving the rest of
    ``src/partial.py`` in the corpus, which is the cut-inside-a-file case this
    whole helper exists to prevent.

    So the row has to actually be a match row: ``path:<digits>:``. A path cannot
    contain ``:``, so the first one delimits the complete path. Context rows
    (``path-N-body``) return ``None``; they belong to whichever file surrounds
    them, and the caller attributes them by prefix.
    """
    m = _MATCH_ROW_RE.match(row)
    return m.group("path") if m else None


def _trim_to_file_boundary(rows: list[str], cut: int) -> int:
    """Back ``cut`` up so it lands between files, never inside one.

    Two passes, because a file's rows straddle the cut in two different ways.

    Backwards first, over the partial file the cut landed in. Its context rows
    are attributed by path prefix rather than by "the nearest match row" —
    treating every context row as part of the file being dropped would also
    swallow the *previous* file's trailing context.

    Then again, over what is now at the end. `-B`/`-C` context precedes its
    match row, so when the cut falls inside a *new* file's leading context the
    backward search finds the previous file and the first pass has nothing to
    do: the orphan context rows, and the `--` separator above them, stay. That
    leaves a file represented by context alone, which is not a shape ripgrep
    emits — precisely what this helper exists to keep out of the corpus.
    """
    target = next((f for i in range(cut - 1, -1, -1) if (f := _row_file(rows[i]))), None)
    if target is None:
        return cut
    prefix = target + "-"
    while cut > 1 and (_row_file(rows[cut - 1]) == target or rows[cut - 1].startswith(prefix)):
        cut -= 1

    kept = next((f for i in range(cut - 1, -1, -1) if (f := _row_file(rows[i]))), None)
    kept_prefix = f"{kept}-" if kept is not None else None
    while cut > 1 and _row_file(rows[cut - 1]) is None:
        if kept_prefix is not None and rows[cut - 1].startswith(kept_prefix):
            break
        cut -= 1
    return cut or MAX_ROWS


def previous_best(content: str) -> str:
    """What ``compact_lossless`` would have returned before the tree fold."""
    best = content
    for candidate, inverse in (
        (search_heading(content), search_unheading),
        (search_dir_heading(content), search_dir_unheading),
    ):
        if inverse(candidate) == content and len(candidate) < len(best):
            best = candidate
    return best


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sample", action="store_true", help="print a folded excerpt")
    args = parser.parse_args()

    if shutil.which("rg") is None:
        print("ripgrep (rg) not on PATH — cannot build the corpus", file=sys.stderr)
        return 2

    header = f"{'query':22} {'raw':>8} {'before':>8} {'after':>8} {'vs raw':>8} {'vs before':>10}"
    print(header)
    print("-" * len(header))

    total_raw = total_before = total_after = 0
    for label, pattern, flags in QUERIES:
        content = collect(pattern, flags)
        if not content.strip():
            print(f"{label:22} (no matches)")
            continue
        before = previous_best(content)
        after = compact_lossless(content, "search")
        # Both must be exactly recoverable or the number is meaningless.
        assert before == content or search_fold_recovers(before, content), label
        assert after == content or search_fold_recovers(after, content), label

        raw_t, before_t, after_t = (
            _estimate_tokens(content),
            _estimate_tokens(before),
            _estimate_tokens(after),
        )
        total_raw += raw_t
        total_before += before_t
        total_after += after_t
        print(
            f"{label:22} {raw_t:8} {before_t:8} {after_t:8} "
            f"{1 - after_t / raw_t:7.1%} {1 - after_t / before_t:10.1%}"
        )

    print("-" * len(header))
    print(
        f"{'TOTAL':22} {total_raw:8} {total_before:8} {total_after:8} "
        f"{1 - total_after / total_raw:7.1%} {1 - total_after / total_before:10.1%}"
    )

    if args.sample:
        content = collect(*QUERIES[0][1:])
        print("\n--- folded excerpt ---")
        print("\n".join(compact_lossless(content, "search").split("\n")[:24]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
