class TestBlockCap:
    """E1: the block must not grow without bound."""

    def test_small_block_is_untouched(self):
        recs = [_sized_rec(f"S{i}", 1000) for i in range(3)]

        assert _apply_block_cap(recs) == recs

    def test_oversized_block_is_capped(self):
        recs = [_sized_rec(f"S{i}", 1000 - i, body_chars=600) for i in range(40)]

        kept = _apply_block_cap(recs)

        assert len(kept) < len(recs)
        rendered = _build_section(recs)
        assert _estimate_tokens(rendered) <= MAX_BLOCK_TOKENS

    def test_eviction_is_by_ascending_estimated_tokens_saved(self):
        recs = [
            _sized_rec("Valuable", 9000, body_chars=2000),
            _sized_rec("Cheap", 1, body_chars=2000),
            _sized_rec("Middling", 500, body_chars=2000),
        ]

        # Only as many as needed are evicted, cheapest-first.
        assert [r.section for r in _apply_block_cap(recs, max_tokens=1200)] == [
            "Valuable",
            "Middling",
        ]
        assert [r.section for r in _apply_block_cap(recs, max_tokens=700)] == ["Valuable"]

    def test_survivors_keep_their_original_order(self):
        recs = [
            _sized_rec("A", 10, body_chars=1500),
            _sized_rec("B", 9000, body_chars=1500),
            _sized_rec("C", 8000, body_chars=1500),
        ]

        kept = [r.section for r in _apply_block_cap(recs, max_tokens=1200)]

        assert kept == ["B", "C"]

    def test_never_evicts_everything(self):
        recs = [_sized_rec("Huge", 5, body_chars=40_000)]

        kept = _apply_block_cap(recs, max_tokens=100)

        assert [r.section for r in kept] == ["Huge"]

    def test_empty_input(self):
        assert _apply_block_cap([]) == []


class TestSidecarProvenance:
    """E3: provenance and per-section estimates move out of the context file."""

    def test_apply_writes_sidecar_outside_the_project(self, tmp_path, isolated_sidecar):
        proj = _project(tmp_path)
        target = proj.project_path / "CLAUDE.local.md"
        rec = Recommendation(
            target=RecommendationTarget.CONTEXT_FILE,
            section="Environment",
            content="- Use uv",
            estimated_tokens_saved=1234,
        )

        ClaudeCodeWriter().write([rec], proj, dry_run=False)

        sidecar = _sidecar_path(target)
        assert sidecar.exists()
        assert tmp_path / "hr-workspace" in sidecar.parents
        payload = json.loads(sidecar.read_text())
        assert payload["sections"]["environment"] == 1234
        assert payload["generated_at"].endswith("Z")
        # Provenance must NOT be in the (context-resident) block.
        assert "generated_at" not in target.read_text()

    def test_dry_run_writes_no_sidecar(self, tmp_path, isolated_sidecar):
        proj = _project(tmp_path)
