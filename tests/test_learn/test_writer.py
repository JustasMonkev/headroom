def _sized_rec(section: str, saved: int, body_chars: int = 200) -> Recommendation:
    return Recommendation(
        target=RecommendationTarget.CONTEXT_FILE,
        section=section,
        content="- " + ("x" * body_chars),
        estimated_tokens_saved=saved,
    )


class TestBlockIsByteStable:
    """E3: no date line, no per-section token annotations."""

    def test_identical_recommendations_render_identical_bytes(self):
        recs = [_sized_rec("Environment", 900)]

        assert _build_section(recs) == _build_section(list(recs))

    def test_block_has_no_date_line(self):
        block = _build_section([_sized_rec("Environment", 900)])

        assert "on 20" not in block
        assert block.splitlines()[2] == (
            "*Auto-generated by `headroom learn` — do not edit manually*"
        )

    def test_block_has_no_token_annotations(self):
        block = _build_section([_sized_rec("Environment", 15000)])

        assert "tokens/session saved" not in block
        assert "15,000" not in block

    def test_rerun_with_unchanged_rules_does_not_touch_the_file(self, tmp_path, isolated_sidecar):
        """The whole point: a no-op run must not churn bytes downstream.

        CLAUDE.local.md / AGENTS.md are loaded into every request of every
        future session, so a gratuitous rewrite busts downstream prefix caches.
        """
        proj = _project(tmp_path)
        writer = ClaudeCodeWriter()
        recs = [_rec(RecommendationTarget.CONTEXT_FILE, "Environment", "- Use uv run python")]

        writer.write(recs, proj, dry_run=False)
        first = (proj.project_path / "CLAUDE.local.md").read_bytes()
        writer.write(recs, proj, dry_run=False)
